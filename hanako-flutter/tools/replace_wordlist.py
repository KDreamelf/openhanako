with open('lib/identity/word_dict.dart', 'r', encoding='utf-8') as f:
    text = f.read()

m = re.search(r'(_hanakoWordlist\s*=\s*\[)(.*?)(\s*\];)', text, re.DOTALL)
arr_body = m.group(2)
words = re.findall(r"'([^']+)'", arr_body)
assert len(words) == 2048, f'expected 2048, got {len(words)}'

# 整段替换（先做，免得 single 替换跟整段冲突）
for seg_name, seg in wholesale_segments.items():
    old_set = seg['old']
    new_set = seg['new']
    for start in range(len(words) - len(old_set) + 1):
        if words[start:start+len(old_set)] == old_set:
            for k, w in enumerate(new_set):
                words[start+k] = w
            print(f'整段替换 [{seg_name}] @{start}: {len(old_set)} 词')
            break
    else:
        print(f'!! 未找到整段 {seg_name}')

# 单个替换
applied = 0
not_found = []
for old, new in replacements.items():
    found = False
    for i, w in enumerate(words):
        if w == old:
            words[i] = new
            applied += 1
            found = True
            break
    if not found:
        not_found.append(old)

print(f'单个替换：{applied} / {len(replacements)}')
if not_found:
    print(f'未找到：{not_found}')

