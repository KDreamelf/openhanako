seen = {}
dups = []
for i, w in enumerate(words):
    if w in seen:
        dups.append((w, seen[w], i))
    else:
        seen[w] = i
print(f'\n词数 {len(words)}, 唯一 {len(seen)}, 重复 {len(dups)}')
for w, a, b in dups:
    print(f'  DUP {a} & {b}: {w}')

# 写回，保留原行结构
orig_lines = arr_body.split('\n')
new_lines = []
idx = 0
for ln in orig_lines:
    s = ln.rstrip()
    if '//' in s and "'" not in s:
        new_lines.append(s)
        continue
    if "'" in s:
        cnt = len(re.findall(r"'[^']+'", s))
        if idx + cnt > len(words):
            new_lines.append(s)
            continue
        leading = re.match(r'^(\s*)', s).group(1)
        new_words = words[idx:idx+cnt]
        idx += cnt
        new_lines.append(leading + ', '.join("'" + w + "'" for w in new_words) + ',')
        continue
    new_lines.append(s)

new_arr_body = '\n'.join(new_lines)
new_text = text[:m.start(2)] + new_arr_body + text[m.end(2):]

with open('lib/identity/word_dict.dart', 'w', encoding='utf-8') as f:
    f.write(new_text)
print('字典已写回')

if dups:
    sys.exit(1)
