// lib/identity/word_dict.dart
//
// 中文助记词字典（2048 词）。
//
// 用途：把 132 bit 熵均匀地映射到 12 个易记忆的中文名词，等价于 BIP-39 的
//      英文 wordlist，但全部使用中文名词。每个名词分配一个 0..2047 的 ID，
//      ID 即 11 bit 索引。
//
// 编制约束（与 MVP §3.5 / §10.5 对齐）：
//   1. 全部为名词，禁止动词 / 形容词 / 副词；
//   2. 在中文母语者直觉下意义无歧义；
//   3. 覆盖面广（自然 / 动植物 / 食物 / 物品 / 建筑 / 抽象意象等），
//      让 LLM 编故事时有足够的画面感；
//   4. 易于联想，避免生僻字；
//   5. 字典版本固定，不可随便改顺序——一旦某个版本的助记词流入用户手中，
//      该版本字典在客户端永远存在。新增词只允许追加（保留旧 ID 不变）。
//
// 当前状态：
//   - **草案 v1.0-draft**：2048 词已填齐，可让 BIP-39 中文变体派生跑通。
//   - **TODO**：发版前需人工逐一审过，去歧义、去近义、去文化敏感词。
//     审完后版本号升 v1.0，落地后字典禁止改动顺序。
//
// 与 master-server 的协同：
//   字典是协同物料。子体生成的助记词必须能被服务端理解（恢复期会把字典
//   一起发给 LLM 解析模糊故事）。本文件最终定稿时必须与 master-server 端
//   的字典文件完全一致——发版前需双方校对。

/// 字典版本号。一旦正式发版，所有客户端必须能识别。新增词只追加在末尾。
const String hanakoWordlistVersion = 'v1.0-rc3';

/// 当前字典实际词数。
int get hanakoWordlistSize => _hanakoWordlist.length;

/// 字典发布版的目标词数。
const int hanakoWordlistTargetSize = 2048;

/// 词 → ID（0-based）。线性扫表，初始化时一次性建索引。
final Map<String, int> _wordToId = () {
  final map = <String, int>{};
  for (var i = 0; i < _hanakoWordlist.length; i++) {
    final w = _hanakoWordlist[i];
    if (map.containsKey(w)) {
      throw StateError('字典出现重复词：$w（位置 ${map[w]} 与 $i）');
    }
    map[w] = i;
  }
  return map;
}();

/// 通过 ID 取词（越界返回 null）。
String? wordById(int id) {
  if (id < 0 || id >= _hanakoWordlist.length) return null;
  return _hanakoWordlist[id];
}

/// 通过词取 ID（不存在返回 null）。
int? idByWord(String word) => _wordToId[word.trim()];

/// 整本字典只读视图（用于把字典发给 LLM 做语义匹配）。
